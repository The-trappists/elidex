"""Exports: node-link JSON, Cytoscape elements (for the web UI) and a Cypher script (for Neo4j)."""

from __future__ import annotations

import json
from datetime import datetime
from typing import Any

import networkx as nx

_TEMPORAL = {"valid_from", "valid_to", "sent_at", "started_at", "at"}


def _plain(value: Any) -> Any:
    if isinstance(value, datetime):
        return value.isoformat()
    if isinstance(value, (list, tuple)):
        return [_plain(v) for v in value]
    return value


def _props(data: dict, skip: tuple[str, ...] = ()) -> dict:
    return {k: _plain(v) for k, v in data.items() if v is not None and v != [] and k not in skip}


def to_node_link(g: nx.MultiDiGraph) -> dict:
    return {
        "nodes": [{"id": n, **_props(d)} for n, d in g.nodes(data=True)],
        "edges": [{"source": u, "target": v, **_props(d)} for u, v, d in g.edges(data=True)],
    }


def to_cytoscape(g: nx.MultiDiGraph) -> list[dict]:
    """Cytoscape.js `elements`; `payload` and long text stay out to keep it light."""
    els = [{"group": "nodes", "data": {"id": n, **_props(d, skip=("payload", "text"))}} for n, d in g.nodes(data=True)]
    els += [
        {"group": "edges", "data": {"id": f"{u}|{k}|{v}", "source": u, "target": v, "label": k, **_props(d)}}
        for u, v, k, d in g.edges(keys=True, data=True)
    ]
    return els


def _cypher_value(key: str, value: Any) -> str:
    if isinstance(value, datetime):
        return f'localdatetime("{value.isoformat()}")'
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, (list, tuple)):
        return "[" + ", ".join(_cypher_value(key, v) for v in value) + "]"
    return json.dumps(str(value), ensure_ascii=False)


def _cypher_map(data: dict) -> str:
    items = [f"`{k}`: {_cypher_value(k, v)}" for k, v in data.items() if v is not None and v != [] and k != "kind"]
    return "{" + ", ".join(items) + "}"


def to_cypher(g: nx.MultiDiGraph) -> str:
    """An idempotent Cypher script (MERGE): paste it in Neo4j Browser or run it with cypher-shell."""
    lines = ["// Generated by `ctx graph export --format cypher`. Safe to re-run (MERGE)."]
    for kind in sorted({d["kind"] for _, d in g.nodes(data=True)}):
        lines.append(f"CREATE CONSTRAINT {kind.lower()}_id IF NOT EXISTS FOR (n:{kind}) REQUIRE n.id IS UNIQUE;")
    for n, d in g.nodes(data=True):
        lines.append(f"MERGE (n:{d['kind']} {{id: {json.dumps(n, ensure_ascii=False)}}}) SET n += {_cypher_map(d)};")
    for u, v, k, d in g.edges(keys=True, data=True):
        su, sv = g.nodes[u]["kind"], g.nodes[v]["kind"]
        props = {x: y for x, y in d.items() if x != "type"}
        set_clause = f" SET r += {_cypher_map(props)}" if props else ""
        lines.append(
            f"MATCH (a:{su} {{id: {json.dumps(u, ensure_ascii=False)}}}), (b:{sv} {{id: {json.dumps(v, ensure_ascii=False)}}}) "
            f"MERGE (a)-[r:{k}]->(b){set_clause};"
        )
    return "\n".join(lines) + "\n"
